"""Evidence-bounded experimental-method extraction and analysis templates.

The extractor is deliberately lexical.  It makes every returned statement
reviewable against a chunk already authorized for the requesting user; it does
not infer missing experimental details or execute generated analysis code.
"""

from __future__ import annotations

import re
from typing import Any

from pydantic import BaseModel, Field

from app.services.local_archive import LocalArchive


class Evidence(BaseModel):
    chunk_id: str
    section: str | None = None
    page: int | None = None
    text: str


class AnalysisAutomation(BaseModel):
    method: str
    script_filename: str
    script: str
    input_template_filename: str
    input_template: str
    input_specification: str


class ExperimentExtraction(BaseModel):
    document_id: str
    title: str
    experimental_workflow: list[Evidence] = Field(default_factory=list)
    materials_and_equipment: list[Evidence] = Field(default_factory=list)
    data_analysis_methods: list[Evidence] = Field(default_factory=list)
    expected_results: list[Evidence] = Field(default_factory=list)
    conclusions: list[Evidence] = Field(default_factory=list)
    automations: list[AnalysisAutomation] = Field(default_factory=list)
    review_note: str


_WORKFLOW = re.compile(r"protocol|procedure|method|methods|prepared|incubat|stain|fix|randomi|sample|实验|方法|处理|固定|染色", re.I)
_MATERIALS = re.compile(r"antibody|reagent|kit|buffer|medium|microscope|sequenc|scanner|centrifuge|equipment|material|试剂|抗体|仪器|设备|培养基", re.I)
_ANALYSIS = re.compile(r"t[- ]?test|anova|regression|linear model|mann.?whitney|wilcoxon|chi.?square|统计|方差分析|回归|显著", re.I)
_RESULTS = re.compile(r"result|finding|outcome|observed|increas|decreas|effect|结果|发现|增加|降低", re.I)
_CONCLUSIONS = re.compile(r"conclusion|conclude|discussion|suggest|demonstrat|总结|结论|表明", re.I)

_T_TEST = """\"\"\"Two-group comparison generated by Lab Agent.\nInput: input.csv with columns group,value. group must have exactly two non-empty labels; value must be numeric.\n\"\"\"\nimport csv\nimport math\nimport statistics\nfrom pathlib import Path\n\ndef main(path='input.csv'):\n    groups = {}\n    with Path(path).open(newline='', encoding='utf-8') as handle:\n        for row in csv.DictReader(handle):\n            groups.setdefault(row['group'].strip(), []).append(float(row['value']))\n    if len(groups) != 2 or any(len(values) < 2 for values in groups.values()):\n        raise ValueError('need exactly two groups with at least two numeric values each')\n    (left, x), (right, y) = groups.items()\n    se = math.sqrt(statistics.variance(x) / len(x) + statistics.variance(y) / len(y))\n    t_value = (statistics.mean(x) - statistics.mean(y)) / se if se else float('nan')\n    print({'groups': [left, right], 'n': [len(x), len(y)], 'means': [statistics.mean(x), statistics.mean(y)], 'welch_t': t_value})\n    print('Review distribution, variance, independence and the study design before interpreting this result.')\n\nif __name__ == '__main__':\n    main()\n"""

_ANOVA = """\"\"\"One-way descriptive ANOVA preparation generated by Lab Agent.\nInput: input.csv with columns group,value. Use a validated statistics package or statistician for inferential testing.\n\"\"\"\nimport csv\nimport statistics\nfrom pathlib import Path\n\ndef main(path='input.csv'):\n    groups = {}\n    with Path(path).open(newline='', encoding='utf-8') as handle:\n        for row in csv.DictReader(handle):\n            groups.setdefault(row['group'].strip(), []).append(float(row['value']))\n    if len(groups) < 2 or any(len(values) < 2 for values in groups.values()):\n        raise ValueError('need at least two groups with at least two numeric values each')\n    print({name: {'n': len(values), 'mean': statistics.mean(values), 'sd': statistics.stdev(values)} for name, values in groups.items()})\n    print('Pre-register contrasts and check normality, homoscedasticity and independence before ANOVA.')\n\nif __name__ == '__main__':\n    main()\n"""

_REGRESSION = """\"\"\"Simple linear-regression preparation generated by Lab Agent.\nInput: input.csv with numeric columns x,y. This script reports a fitted line; assess residuals and study design before inference.\n\"\"\"\nimport csv\nimport statistics\nfrom pathlib import Path\n\ndef main(path='input.csv'):\n    rows = []\n    with Path(path).open(newline='', encoding='utf-8') as handle:\n        rows = [(float(row['x']), float(row['y'])) for row in csv.DictReader(handle)]\n    if len(rows) < 3: raise ValueError('need at least three x,y observations')\n    xs, ys = zip(*rows)\n    slope = sum((x - statistics.mean(xs)) * (y - statistics.mean(ys)) for x, y in rows) / sum((x - statistics.mean(xs)) ** 2 for x in xs)\n    intercept = statistics.mean(ys) - slope * statistics.mean(xs)\n    print({'n': len(rows), 'slope': slope, 'intercept': intercept})\n\nif __name__ == '__main__':\n    main()\n"""


class ExperimentExtractionService:
    def __init__(self, archive: LocalArchive) -> None:
        self.archive = archive

    def extract(self, user_id: str, project_id: str, document_id: str) -> ExperimentExtraction:
        document = self.archive.authorized_document(user_id, project_id, document_id)
        if not document:
            raise LookupError("authorized document was not found")
        chunks = self.archive.document_chunks_for_user(user_id, project_id, document_id)
        evidence = [self._evidence(chunk) for chunk in chunks]
        result = ExperimentExtraction(
            document_id=document_id,
            title=document["title"],
            experimental_workflow=self._matching(evidence, _WORKFLOW, ("method", "protocol", "实验", "方法")),
            materials_and_equipment=self._matching(evidence, _MATERIALS, ("material", "equipment", "reagent", "试剂", "仪器")),
            data_analysis_methods=self._matching(evidence, _ANALYSIS, ("statistical", "analysis", "统计", "分析")),
            expected_results=self._matching(evidence, _RESULTS, ("result", "outcome", "结果")),
            conclusions=self._matching(evidence, _CONCLUSIONS, ("discussion", "conclusion", "结论", "讨论")),
            review_note="自动抽取仅呈现原文证据，必须由研究人员核对原文、适用对象、实验设计和统计假设后使用。",
        )
        analysis_text = "\n".join(item.text for item in result.data_analysis_methods)
        result.automations = self._automations(analysis_text)
        return result

    @staticmethod
    def _evidence(chunk: dict[str, Any]) -> Evidence:
        metadata = chunk["metadata"]
        return Evidence(chunk_id=chunk["id"], section=metadata.get("section"), page=metadata.get("page"), text=chunk["text"])

    @staticmethod
    def _matching(evidence: list[Evidence], pattern: re.Pattern[str], section_terms: tuple[str, ...]) -> list[Evidence]:
        matched = [item for item in evidence if pattern.search(item.text) or any(term in (item.section or "").lower() for term in section_terms)]
        return matched[:8]

    @staticmethod
    def _automations(text: str) -> list[AnalysisAutomation]:
        items: list[AnalysisAutomation] = []
        lowered = text.lower()
        if re.search(r"t[- ]?test|t test|t检验", lowered):
            items.append(AnalysisAutomation(method="Welch two-sample t-test", script_filename="two_group_t_test.py", script=_T_TEST, input_template_filename="two_group_input.csv", input_template="group,value\ncontrol,0.0\ntreatment,0.0\n", input_specification="CSV UTF-8，表头为 group,value；每行一条独立观测；每组至少两条数值记录。"))
        if re.search(r"anova|方差分析", lowered):
            items.append(AnalysisAutomation(method="One-way ANOVA preparation", script_filename="one_way_anova.py", script=_ANOVA, input_template_filename="anova_input.csv", input_template="group,value\ncontrol,0.0\ntreatment_a,0.0\n", input_specification="CSV UTF-8，表头为 group,value；每行一条独立观测；至少两组且每组至少两条数值记录。"))
        if re.search(r"regression|linear model|回归", lowered):
            items.append(AnalysisAutomation(method="Simple linear regression", script_filename="linear_regression.py", script=_REGRESSION, input_template_filename="regression_input.csv", input_template="x,y\n0.0,0.0\n", input_specification="CSV UTF-8，表头为 x,y；每行一条独立观测；至少三条数值记录。"))
        return items
